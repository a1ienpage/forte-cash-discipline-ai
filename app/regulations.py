def _prev_word(text: str, start: int) -> str:
    words = _WORD_RE.findall(text[:start])
    return words[-1] if words else ""


def _is_negated(text: str, start: int) -> bool:
    """Отрицание относится к конкретному слову: «не»/«ни» непосредственно перед ним."""
    return _prev_word(text, start) in ("не", "ни")


def _is_noun_negated(text: str, start: int) -> bool:
    """Отрицание существительного: «без X», «нет X»."""
    return _prev_word(text, start) in ("без", "нет")


def _detect_subject(text: str) -> Tuple[Optional[str], Optional[str]]:
    """Определяет подлежащее клаузы (именительный падеж) и его определение (`второй`, `следующий` и т.п.)."""
    best: Optional[Tuple[int, str, str]] = None
    for role, rx in _ACTOR_NOMINATIVE:
        for m in rx.finditer(text):
            prev = _prev_word(text, m.start())
            if prev in _NON_SUBJECT_PRECEDING:
                continue
            if best is None or m.start() < best[0]:
                best = (m.start(), role, prev)
            break
    if best is None:
        return None, None
    return best[1], best[2] or None


def _split_clauses_with_actors(obs_text: str) -> List[Dict[str, Any]]:
    """
    Разбивает наблюдение на клаузы (простые предикативные части) и определяет для каждой клаузы
    подлежащее-участника (`cashier` / `client` / `other_person` / `system` / `object` / `unspecified`).
    Подлежащее наследуется однородными сказуемыми только в пределах одного предложения и только если
    у клаузы нет собственного подлежащего (R02, R05; ревью 0909, п. 4.2).
    """
    sentences = [
        s.strip()
        for s in re.split(r"[;!?]+|\.(?!\d)|\s+[—–]\s+", (obs_text or "").lower())
        if s and s.strip()
    ]
    split_re = re.compile(
        r",\s*(?:а|но|однако|хотя|тогда как|при этом|в то время как|между тем|когда|где|после чего|затем|пока)\s+"
        r"|\s+(?:а|но|однако|тогда как|при этом|в то время как|пока|затем|после чего)\s+"
        r"|:\s*|,\s+|\s+и\s+"
    )
    clauses: List[Dict[str, Any]] = []
    for sent_idx, sent in enumerate(sentences):
        raw_parts = [re.sub(r"\s+", " ", p).strip() for p in split_re.split(sent)]
        raw_parts = [p for p in raw_parts if p]
        # Короткие бессказуемные части («содержимое», «кассир, возможно,») присоединяются к следующей части,
        # чтобы неопределённость и подлежащее не терялись при разбиении по запятым/союзу «и».
        parts: List[str] = []
        carry = ""
        for idx_p, p in enumerate(raw_parts):
            words = _WORD_RE.findall(p)
            contentless = bool(words) and all(
                w in _CONTENTLESS_WORDS or any(rx.fullmatch(w) for _, rx in _ACTOR_NOMINATIVE) for w in words
            )
            has_next = idx_p + 1 < len(raw_parts)
            next_has_actor = has_next and _detect_subject(raw_parts[idx_p + 1])[0] is not None
            if contentless and len(words) <= 2 and has_next and not (
                _detect_subject(p)[0] is not None and next_has_actor
            ):
                carry = f"{carry} {p}".strip()
                continue
            parts.append(f"{carry} {p}".strip() if carry else p)
            carry = ""
        if carry:
            parts.append(carry)

        prev_actor: Optional[str] = None
        prev_qualifier: Optional[str] = None
        prev_safe_id: str = "default"
        for p in parts:
            role, qualifier = _detect_subject(p)
            if role is None:
                if _OBJECT_START_RE.search(p):
                    role = "object"
                elif prev_actor is not None:
                    role, qualifier = prev_actor, prev_qualifier
                else:
                    role = "unspecified"
            if role in ("cashier", "client", "other_person", "system"):
                prev_actor, prev_qualifier = role, qualifier

            qm = _SAFE_QUALIFIER_RE.search(p)
            if qm and (_SAFE_NOUN_RE.search(p) or _DOOR_RE.search(p)):
                safe_id = qm.group(1)
                prev_safe_id = safe_id
            elif _SAFE_NOUN_RE.search(p) and not qm:
                safe_id = prev_safe_id if prev_safe_id != "default" and not re.search(r"\bсейф\w*", p) else prev_safe_id
            else:
                safe_id = prev_safe_id

            clauses.append(
                {
                    "text": p,
                    "actor": role,
                    "actor_qualifier": qualifier,
                    "sentence_idx": sent_idx,
                    "safe_id": safe_id,
                    "has_negation": bool(re.search(r"\b(?:не|нет|без|никак\w*)\b", p)),
                    "has_uncertainty": bool(_UNCERTAINTY_RE.search(p)),
                }
            )
    return clauses


# --- Извлечение фактов «участник — действие — объект» по каждому необходимому условию -------------
# Каждый экстрактор возвращает список (polarity, clause), где polarity ∈ {"pos", "neg", "unk"}:
#   pos — условие установлено для правильного участника/объекта в этой клаузе;
#   neg — та же клауза прямо опровергает условие (отрицание относится к этому факту);
#   unk — факт относится к условию, но помечен как неразличимый/неопределённый.


def _fx_phone_use(clauses: List[Dict[str, Any]], obs_low: str) -> List[Tuple[str, Dict[str, Any]]]:
    out = []
    for c in clauses:
        t = _LANDLINE_RE.sub(" ", c["text"])
        pm = _PHONE_RE.search(t)
        if not pm or c["actor"] != "cashier":
            continue
        if c["has_uncertainty"]:
            out.append(("unk", c))
            continue
        if _is_noun_negated(t, pm.start()) or _CASH_ABSENT_RE.search(t):
            out.append(("neg", c))
            continue
        action_verbs = list(_PHONE_ACTION_VERB_RE.finditer(t))
        loc_phrases = list(_PHONE_HOLD_LOC_RE.finditer(t))
        if not action_verbs and not loc_phrases:
            continue
        if any(_is_negated(t, lm.start()) for lm in loc_phrases):
            out.append(("neg", c))
            continue
        if action_verbs:
            if not any(not _is_negated(t, v.start()) for v in action_verbs):
                out.append(("neg", c))
                continue
        other = _OTHER_PERSON_ANY_RE.search(t)
        if other:
            talk = _PHONE_TALK_RE.search(t)
            if not (talk and talk.start() < other.start()):
                # Телефон в этой клаузе связан с другим человеком («видит клиента со смартфоном»)
                continue
        out.append(("pos", c))
    return out


def _actor_exit_facts(clauses: List[Dict[str, Any]], role: str) -> List[Tuple[str, Dict[str, Any]]]:
    out = []
    for c in clauses:
        t = c["text"]
        for m in _OBLIQUE_ABSENCE[role].finditer(t):
            if c["has_uncertainty"]:
                out.append(("unk", c))
            elif _is_negated(t, m.start()):
                out.append(("neg", c))
            else:
                out.append(("pos", c))
        if c["actor"] == role:
            for m in _EXIT_VERB_RE.finditer(t):
                if c["has_uncertainty"]:
                    out.append(("unk", c))
                elif _is_negated(t, m.start()):
                    out.append(("neg", c))
                elif _IN_ROOM_DEST_RE.search(t) and not _EXPLICIT_ROOM_EXIT_RE.search(t):
                    out.append(("neg", c))
                else:
                    out.append(("pos", c))
    return out


def _fx_cashier_exit(clauses, obs_low):
    return _actor_exit_facts(clauses, "cashier")


def _fx_client_absent(clauses, obs_low):
    out = _actor_exit_facts(clauses, "client")
    for c in clauses:
        t = c["text"]
        if _CLIENT_PRESENCE_OBLIQUE_RE.search(t):
            out.append(("neg", c))
        if c["actor"] == "client" and (c["actor_qualifier"] or "") not in ("предыдущий", "прошлый"):
            for m in _PRESENCE_VERB_RE.finditer(t):
                if not _is_negated(t, m.start()) and not c["has_uncertainty"]:
                    out.append(("neg", c))
    return out


def _cash_desk_polarity(c: Dict[str, Any], sentence_has_cash: bool, require_desk_loc: bool = True) -> Optional[str]:
    t = c["text"]
    partial = bool(_PARTIAL_RE.search(t))
    if _DESK_EMPTY_RE.search(t) and not partial:
        return "neg"
    cm = _CASH_RE.search(t)
    if not cm and not (partial and sentence_has_cash and re.match(r"^(?:" + _ADJ + r"\s+)?(?:част|остальн)", t)):
        return None
    if c["has_uncertainty"]:
        return "unk"
    if cm and (_is_noun_negated(t, cm.start()) or _CASH_ABSENT_RE.search(t)):
        return None if partial else "neg"
    stored = [m for m in _STORED_RE.finditer(t) if not _is_negated(t, m.start())]
    desk = _DESK_LOC_RE.search(t)
    left = _LEFT_STATE_RE.search(t)
    not_removed = _NOT_REMOVED_RE.search(t)
    if stored and not not_removed:
        return None if partial else "neg"
    if _STORAGE_LOC_RE.search(t) and not desk:
        return None
    if _NON_DESK_LOC_RE.search(t) and not desk:
        return None if partial else "neg"
    if not (desk or left or not_removed):
        return None
    if desk and _is_negated(t, desk.start()):
        return "neg"
    if left and _is_negated(t, left.start()):
        return "neg"
    if require_desk_loc and not desk:
        return None
    return "pos"


def _sentence_cash_map(clauses: List[Dict[str, Any]], obs_low: str) -> bool:
    return bool(_CASH_RE.search(obs_low))


def _fx_cash_on_desk(clauses, obs_low):
    has_cash = _sentence_cash_map(clauses, obs_low)
    out = []
    for c in clauses:
        pol = _cash_desk_polarity(c, has_cash, require_desk_loc=True)
        if pol:
            out.append((pol, c))
    return out


def _fx_previous_cash(clauses, obs_low):
    has_cash = _sentence_cash_map(clauses, obs_low)
    prev_client_mentioned = bool(_PREVIOUS_CLIENT_MENTION_RE.search(obs_low))
    out = []
    for c in clauses:
        t = c["text"]
        pol = _cash_desk_polarity(c, has_cash, require_desk_loc=False)
        if pol is None:
            continue
        if pol in ("neg", "unk"):
            out.append((pol, c))
            continue
        if _OWNER_CURRENT_RE.search(t):
            continue
        if _OWNER_PREVIOUS_RE.search(t) or (_LEFTOVER_RE.search(t) and prev_client_mentioned):
            out.append(("pos", c))
    return out


def _fx_next_client(clauses, obs_low):
    out = []
    for c in clauses:
        t = c["text"]
        am = _ARRIVE_RE.search(t)
        if not am:
            continue
        is_next = bool(_NEXT_CLIENT_RE.search(t))
        if not is_next and not (
            c["actor"] == "client" and (c["actor_qualifier"] or "") not in ("предыдущий", "прошлый")
        ):
            continue
        if c["has_uncertainty"]:
            out.append(("unk", c))
        elif _is_negated(t, am.start()):
            out.append(("neg", c))
        else:
            out.append(("pos", c))
    return out


def _fx_recount(clauses, obs_low):
    out = []
    for c in clauses:
        t = c["text"]
        for m in _COUNT_RE.finditer(t):
            if c["actor"] != "cashier":
                continue
            money_ctx = bool(_CASH_RE.search(t)) or bool(_VALUABLES_RE.search(t)) or bool(_COUNTER_RE.search(t))
            if not money_ctx:
                if _NON_CASH_COUNT_OBJ_RE.search(t):
                    out.append(("neg", c))
                continue
            if c["has_uncertainty"]:
                out.append(("unk", c))
            elif _is_negated(t, m.start()):
                out.append(("neg", c))
            else:
                out.append(("pos", c))
            break
    return out


def _safe_mentioned(obs_low: str) -> bool:
    return bool(_SAFE_NOUN_RE.search(obs_low))


def _fx_safe_open(clauses, obs_low):
    safe_any = _safe_mentioned(obs_low)
    out = []
    for c in clauses:
        t = c["text"]
        has_safe = bool(_SAFE_NOUN_RE.search(t)) or (bool(_DOOR_RE.search(t)) and safe_any)
        if not has_safe:
            continue
        qualified = bool(_DISTINCT_OBJECT_QUALIFIER_RE.search(t))
        if c["has_uncertainty"]:
            if not qualified:
                out.append(("unk", c))
            continue
        open_m = [m for m in _OPEN_RE.finditer(t) if not _is_negated(t, m.start())]
        neg_open = [m for m in _OPEN_RE.finditer(t) if _is_negated(t, m.start())]
        not_closed = _NOT_CLOSED_RE.search(t)
        closed = [m for m in _CLOSED_RE.finditer(t) if not _is_negated(t, m.start())]
        if open_m or not_closed:
            out.append(("pos", c))
        elif (closed or neg_open) and not qualified:
            out.append(("neg", c))
    return out


def _fx_safe_contents(clauses, obs_low):
    safe_any = _safe_mentioned(obs_low)
    open_safe_ids = {
        c.get("safe_id", "default")
        for pol, c in _fx_safe_open(clauses, obs_low)
        if pol == "pos"
    }
    empty_safe_ids = set()
    for c in clauses:
        t = c["text"]
        if _SAFE_EMPTY_RE.search(t) and not _DESK_EMPTY_RE.search(t):
            empty_safe_ids.add(c.get("safe_id", "default"))

    out = []
    for c in clauses:
        t = c["text"]
        sid = c.get("safe_id", "default")
        qualified = bool(_DISTINCT_OBJECT_QUALIFIER_RE.search(t))
        if _SAFE_EMPTY_RE.search(t) and not _DESK_EMPTY_RE.search(t):
            if not qualified or sid in open_safe_ids:
                out.append(("neg", c))
            continue
        vm = _VALUABLES_RE.search(t)
        in_other_container = bool(_OTHER_CONTAINER_LOC_RE.search(t)) and not bool(_SAFE_NOUN_RE.search(t))
        in_safe = (
            bool(_SAFE_INTERIOR_LOC_RE.search(t)) or bool(_SAFE_WITH_VALUABLES_RE.search(t))
        ) and not in_other_container
        contents_word = _CONTENTS_VISIBLE_RE.search(t)
        if c["has_uncertainty"] and (vm or contents_word or (in_safe and safe_any)):
            if not qualified or sid in open_safe_ids:
                out.append(("unk", c))
            continue
        if vm and in_safe and safe_any:
            if _DESK_LOC_RE.search(t):
                continue
            if _is_noun_negated(t, vm.start()) or _CASH_ABSENT_RE.search(t):
                if not qualified or sid in open_safe_ids:
                    out.append(("neg", c))
                continue
            if open_safe_ids and sid not in open_safe_ids and "default" not in open_safe_ids:
                continue
            if sid in empty_safe_ids:
                continue
            out.append(("pos", c))
        elif contents_word and safe_any:
            vis = re.search(r"\bвидн\w*|\bвиден\b", t)
            if vis and not _is_negated(t, vis.start()):
                if open_safe_ids and sid not in open_safe_ids and "default" not in open_safe_ids:
                    continue
                if sid in empty_safe_ids:
                    continue
                out.append(("pos", c))
    return out


def _fx_cashier_not_operating_safe(clauses, obs_low):
    out = []
    for c in clauses:
        t = c["text"]
        if _DESK_WORK_NOMINAL_RE.search(t) and not c["has_uncertainty"]:
            out.append(("pos", c))
            continue
        if c["actor"] != "cashier" or c["has_uncertainty"]:
            continue
        not_used = _SAFE_NOT_USED_RE.search(t)
        in_use = [m for m in _SAFE_IN_USE_RE.finditer(t) if not _is_negated(t, m.start())]
        if in_use and not not_used:
            out.append(("neg", c))
            continue
        if not_used:
            out.append(("pos", c))
            continue
        dw = _DESK_WORK_RE.search(t)
        if dw and not _is_negated(t, dw.start()):
            out.append(("pos", c))
    return out


def _fx_bag_on_desk(clauses, obs_low):
    out = []
    for c in clauses:
        t = c["text"]
        bm = _BAG_RE.search(t)
        if not bm or _PERSONAL_BAG_RE.search(t):
            continue
        qualified = bool(_DISTINCT_OBJECT_QUALIFIER_RE.search(t))
        if c["has_uncertainty"]:
            out.append(("unk", c))
            continue
        stored = [m for m in _STORED_RE.finditer(t) if not _is_negated(t, m.start())]
        desk = _DESK_LOC_RE.search(t)
        if stored or ((_STORAGE_LOC_RE.search(t) or _NON_DESK_LOC_RE.search(t)) and not desk):
            if not qualified:
                out.append(("neg", c))
            continue
        left = _LEFT_STATE_RE.search(t)
        if (desk and _is_negated(t, desk.start())) or (left and _is_negated(t, left.start())) or _is_noun_negated(t, bm.start()):
            out.append(("neg", c))
            continue
        if desk:
            out.append(("pos", c))
    return out


def _fx_bag_accepted(clauses, obs_low):
    out = []
    bag_named = bool(_BAG_RE.search(obs_low))
    for c in clauses:
        t = c["text"]
        if not _BAG_RE.search(t) and not (bag_named and re.search(r"\b(?:её|ее|его|их)\b", t)):
            continue
        pm = _ACCEPT_PASSIVE_RE.search(t)
        if pm:
            if c["has_uncertainty"]:
                out.append(("unk", c))
            elif _is_negated(t, pm.start()):
                out.append(("neg", c))
            else:
                out.append(("pos", c))
            continue
        if c["actor"] != "cashier":
            continue
        am = _ACCEPT_RE.search(t)
        if not am:
            continue
        if c["has_uncertainty"]:
            out.append(("unk", c))
        elif _is_negated(t, am.start()):
            out.append(("neg", c))
        else:
            out.append(("pos", c))
    return out


def _fx_seal_unchecked(clauses, obs_low):
    out = []
    performed = []
    for c in clauses:
        t = c["text"]
        if c["actor"] in ("client", "other_person", "system"):
            continue
        for vm in _CHECK_VERB_RE.finditer(t):
            if not _CHECK_OBJECT_RE.search(t):
                continue
            if c["has_uncertainty"]:
                out.append(("unk", c))
            elif _is_negated(t, vm.start()) or _is_noun_negated(t, vm.start()):
                out.append(("pos", c))
            else:
                performed.append(c)
            break
    if not any(p == "pos" for p, _ in out) and performed:
        out.append(("neg", performed[0]))
    return out


def _fx_belongings(clauses, obs_low):
    out = []
    for c in clauses:
        t = c["text"]
        bm = _BELONGINGS_RE.search(t)
        if not bm or _BELONGINGS_EXCLUDED_RE.search(t):
            continue
        if c["actor"] in ("client", "other_person"):
            continue
        desk = _DESK_LOC_RE.search(t)
        left = _LEFT_STATE_RE.search(t)
        if not desk:
            if _NON_DESK_LOC_RE.search(t):
                out.append(("neg", c))
            continue
        if c["has_uncertainty"]:
            out.append(("unk", c))
        elif (
            _is_negated(t, desk.start())
            or _is_noun_negated(t, bm.start())
            or (left and _is_negated(t, left.start()))
        ):
            out.append(("neg", c))
        else:
            out.append(("pos", c))
    return out


